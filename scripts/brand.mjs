// Generates the logo files in brand/logo, the favicons in public/ and src/lib/wordmark.ts.
//   node scripts/brand.mjs
// The geometry lives in src/lib/marks.ts. The active option is set in src/lib/brand.ts.
// The wordmark is Lato Semibold (SIL Open Font License) converted to outlines; the font
// file is read from the system fonts directory, so no font is added to the repository.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';
import sharp from 'sharp';
import { markMonoSvg, markOptions, markPalettes, markSvg } from '../src/lib/marks.ts';
import { activeMark } from '../src/lib/brand.ts';
import { lockup } from '../src/lib/lockup.ts';

const FONT = '/usr/share/fonts/truetype/lato/Lato-Semibold.ttf';
const out = (p) => new URL(`../${p}`, import.meta.url);

const r1 = (n) => String(Math.round(n * 10) / 10);
const pathData = (cmds) =>
  cmds
    .map((c) => {
      const n = { M: ['x', 'y'], L: ['x', 'y'], Q: ['x1', 'y1', 'x', 'y'], C: ['x1', 'y1', 'x2', 'y2', 'x', 'y'], Z: [] }[c.type];
      return c.type + n.map((k) => r1(c[k])).join(' ');
    })
    .join('');

// ---- wordmark outlines (font size 100, baseline at y = 0, left edge at x = 0) ----
const font = opentype.parse(readFileSync(FONT).buffer.slice(0));
const word = 'sympoies';
const path = font.getPath(word, 0, 0, 100, { kerning: true });
const box = path.getBoundingBox();
path.commands.forEach((c) => {
  for (const k of ['x', 'x1', 'x2']) if (typeof c[k] === 'number') c[k] -= box.x1;
});
const wordmark = {
  d: pathData(path.commands),
  width: Math.round((box.x2 - box.x1) * 10) / 10,
  xHeight: font.tables.os2.sxHeight / (font.unitsPerEm / 100),
  descender: Math.round(box.y2 * 10) / 10,
};
writeFileSync(
  out('src/lib/wordmark.ts'),
  `// Generated by scripts/brand.mjs: the word "${word}" as outlines (font size 100, baseline at y = 0).\nexport const wordmark = ${JSON.stringify(wordmark, null, 2)} as const;\n`,
);

// ---- logo files ----
const light = markPalettes.light;
const dark = markPalettes.dark;

function markFile(option, fill, size = 128, levels = 3, background = null) {
  const bg = background ? `<rect width="${size}" height="${size}" fill="${background}"/>` : '';
  const r = size / 2 - 1;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">${bg}${markSvg(option, size / 2, size / 2, r, fill, levels)}</svg>\n`;
}

function lockupFile(option, fill, textColor) {
  const l = lockup(option, fill, textColor);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${l.width} ${l.height}" width="${l.width}" height="${l.height}">${l.body}</svg>\n`;
}

mkdirSync(out('brand/logo'), { recursive: true });
for (const { id } of markOptions) {
  writeFileSync(out(`brand/logo/mark-${id}.svg`), markFile(id, (k) => light[k]));
  writeFileSync(out(`brand/logo/mark-${id}-on-dark.svg`), markFile(id, (k) => dark[k]));
  writeFileSync(out(`brand/logo/mark-${id}-small.svg`), markFile(id, (k) => light[k], 64, 2));
  writeFileSync(out(`brand/logo/lockup-${id}.svg`), lockupFile(id, (k) => light[k], '#122D4A'));
  writeFileSync(out(`brand/logo/lockup-${id}-on-dark.svg`), lockupFile(id, (k) => dark[k], '#F3EEEA'));
  for (const [name, color] of [['mono', '#122D4A'], ['mono-white', '#FFFFFF']]) {
    writeFileSync(
      out(`brand/logo/mark-${id}-${name}.svg`),
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" width="128" height="128">${markMonoSvg(id, 128, color, 'mono')}</svg>\n`,
    );
  }
}

// ---- favicons for the active option ----
const vars = (p) => `--k-dark:${p.dark};--k-mid:${p.mid};--k-bright:${p.bright};--k-paper:${p.paper}`;
const faviconBody = markSvg(activeMark, 32, 32, 31, (k) => `var(--k-${k})`, 2);
writeFileSync(
  out('public/favicon.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><style>:root{${vars(light)}}@media (prefers-color-scheme:dark){:root{${vars(dark)}}}</style>${faviconBody}</svg>\n`,
);

async function png(svg, size, file) {
  await sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png().toFile(new URL(`../${file}`, import.meta.url).pathname);
}
const plate = (size, r, radius) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" rx="${radius}" fill="#F3EEEA"/>${markSvg(activeMark, size / 2, size / 2, r, (k) => light[k], 2)}</svg>`;
await png(plate(64, 28, 12), 32, 'public/favicon-32.png');
await png(plate(180, 68, 0), 180, 'public/apple-touch-icon.png');
mkdirSync(out('brand/logo/png'), { recursive: true });
await png(markFile(activeMark, (k) => light[k], 1024, 4), 1024, 'brand/logo/png/mark.png');
await sharp(Buffer.from(lockupFile(activeMark, (k) => light[k], '#122D4A')), { density: 600 })
  .png()
  .toFile(new URL('../brand/logo/png/lockup.png', import.meta.url).pathname);

console.log(`wordmark ${wordmark.width}x, wrote logos for ${markOptions.map((o) => o.id).join(', ')}; active ${activeMark}`);
